"""Deterministic design.md for `scieflow design render` (M-D1 plan section 5.2).

Same design, same bytes: no clock and no environment. The first line names the generator and the
content hash, so a stale design.md is visible. The sections appear in the plan's fixed order.
"""

from __future__ import annotations


def _cell(value) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _join(value) -> str:
    if isinstance(value, list):
        return ", ".join(_cell(item) for item in value) if value else "none"
    return _cell(value) if value is not None else "none"


def _table(header: list, rows: list) -> list:
    if not rows:
        return ["None recorded."]
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return lines


def _as_dicts(value) -> list:
    return [item for item in value if isinstance(item, dict)] if isinstance(value, list) else []


def _pairs(value) -> list:
    """(key, value) pairs of a mapping sorted by key; anything that is not a mapping has none."""
    return sorted(value.items(), key=lambda pair: str(pair[0])) if isinstance(value, dict) else []


def _sample_size_lines(sample, power) -> list:
    if not isinstance(sample, dict):
        return ["No sample size is recorded."]
    method = sample.get("method")
    lines = [f"Method: {_cell(method)}."]
    if method == "power":
        lines.append(f"Power file: {_cell(sample.get('power_file'))}.")
        if isinstance(power, dict):
            assumptions = power.get("assumptions") if isinstance(power.get("assumptions"), list) else []
            lines.append(f"Family: {_cell(power.get('family'))} (solved for {_cell(power.get('solve'))}).")
            lines.append("Inputs: " + "; ".join(f"{_cell(k)} = {_cell(v)}"
                                               for k, v in _pairs(power.get("inputs"))) + ".")
            lines.append("Result: " + "; ".join(f"{_cell(k)} = {_cell(v)}"
                                               for k, v in _pairs(power.get("result"))) + ".")
            lines.append("Assumptions: " + "; ".join(_cell(a) for a in assumptions) + ".")
        else:
            lines.append("The power file is not readable; see the check result.")
    elif method == "fixed":
        lines.append(f"n = {_cell(sample.get('n'))}. Rationale: {_cell(sample.get('rationale'))}.")
    elif method == "not-applicable":
        lines.append(f"Rationale: {_cell(sample.get('rationale'))}.")
    return lines


def _sap_lines(sap) -> list:
    if not isinstance(sap, dict):
        return ["No analysis plan is recorded."]
    lines = ["### Estimands", ""]
    lines += _table(["id", "outcome", "population", "summary measure"],
                    [[e.get("id"), e.get("outcome"), e.get("population"), e.get("summary_measure")]
                     for e in _as_dicts(sap.get("estimands"))]) + [""]
    lines += ["### Outcomes", ""]
    lines += _table(["id", "variable", "priority", "test", "metric"],
                    [[o.get("id"), o.get("variable"), o.get("priority"), o.get("test"), o.get("metric")]
                     for o in _as_dicts(sap.get("outcomes"))]) + [""]
    missing = sap.get("missing_data")
    lines += ["### Missing data", "",
              f"Strategy: {_cell(missing.get('strategy'))}." if isinstance(missing, dict)
              else "None recorded.", ""]
    mult = sap.get("multiplicity")
    lines += ["### Multiplicity", "",
              f"Method: {_cell(mult.get('method'))}, alpha {_cell(mult.get('alpha'))}." if isinstance(mult, dict)
              else "None recorded.", ""]
    lines += ["### Sensitivity analyses", ""]
    lines += _table(["id", "description"], [[s.get("id"), s.get("description")]
                                           for s in _as_dicts(sap.get("sensitivity"))]) + [""]
    interim = sap.get("interim")
    lines += ["### Interim analyses", "",
              f"Planned: {_cell(interim.get('planned'))}." if isinstance(interim, dict)
              else "None recorded.", ""]
    exploratory = sap.get("exploratory")
    split = exploratory.get("split") if isinstance(exploratory, dict) else None
    if isinstance(split, dict):
        lines.append(f"Exploratory split: fraction {_cell(split.get('fraction'))}, seed "
                     f"{_cell(split.get('seed'))}, stratified by {_join(split.get('stratify_by'))}; "
                     f"fdr {_cell(exploratory.get('fdr'))}.")
    else:
        lines.append("No exploratory split is recorded.")
    return lines


def render(design: dict, report, digest: str, *, power=None, guidelines=None) -> str:
    """The design.md text. `guidelines` maps a checklist id to its verification status."""
    guidelines = guidelines or {}
    out = [f"<!-- generated by scieflow design render from design.yml sha256 {digest}; do not edit -->",
           f"# {_cell(design.get('title'))}", ""]

    def section(heading: str, lines: list) -> None:
        out.append(heading)
        out.append("")
        out.extend(lines)
        out.append("")

    section("## Study type", [f"{_cell(design.get('study_type'))}"])

    pico = design.get("pico") if isinstance(design.get("pico"), dict) else {}
    question = [f"Question: {_cell(design.get('question'))}"]
    question += [f"{key.capitalize()}: {_cell(value)}" for key, value in pico.items()
                 if isinstance(key, str)]
    section("## Question and PICO", question)

    section("## Variables", _table(["id", "name", "role", "type", "unit"],
                                   [[v.get("id"), v.get("name"), v.get("role"), v.get("type"), v.get("unit")]
                                    for v in _as_dicts(design.get("variables"))]))
    section("## Groups", _table(["id", "name", "allocation"],
                                [[g.get("id"), g.get("name"), g.get("allocation")]
                                 for g in _as_dicts(design.get("groups"))]))
    section("## Timeline", _table(["id", "label", "at"],
                                  [[t.get("id"), t.get("label"), t.get("at")]
                                   for t in _as_dicts(design.get("timeline"))]))

    sampling = design.get("sampling")
    section("## Sampling", [f"Method: {_cell(sampling.get('method'))}. Inclusion: "
                            f"{_join(sampling.get('inclusion'))}. Exclusion: "
                            f"{_join(sampling.get('exclusion'))}."] if isinstance(sampling, dict)
            else ["None recorded."])

    rand = design.get("randomisation")
    blind = design.get("blinding")
    rand_lines = []
    if isinstance(rand, dict):
        rand_lines.append(f"Randomisation: {_cell(rand.get('method'))} by {_cell(rand.get('unit'))}; "
                          f"stratified by {_join(rand.get('stratified_by'))}.")
    if isinstance(blind, dict):
        rand_lines.append("Blinding: " + ", ".join(f"{k} {_cell(v)}" for k, v in blind.items()) + ".")
    section("## Randomisation and blinding", rand_lines or ["None recorded."])

    section("## Sample size", _sample_size_lines(design.get("sample_size"), power))
    section("## Statistical analysis plan", _sap_lines(design.get("sap")))

    guides = design.get("reporting_guidelines")
    guide_lines = [f"- {_cell(g)}: verification {_cell(guidelines.get(g, 'not in config/reporting'))}"
                   for g in guides if isinstance(g, str)] if isinstance(guides, list) else []
    section("## Reporting guidelines", guide_lines or ["None recorded."])

    data = design.get("data")
    data_lines = []
    if isinstance(data, dict):
        data_lines.append(f"Levels needed: {_join(data.get('levels_needed'))}.")
        data_lines += _table(["path", "level"], [[s.get("path"), s.get("level")]
                                                 for s in _as_dicts(data.get("sources"))])
    section("## Data levels", data_lines or ["None recorded."])

    errors = sorted({p.rule for p in report.errors})
    warnings = sorted({p.rule for p in report.warnings})
    section("## Check result", [f"errors: {len(report.errors)} (rules: {', '.join(errors) or 'none'})",
                                f"warnings: {len(report.warnings)} (rules: {', '.join(warnings) or 'none'})"])
    return "\n".join(out).rstrip("\n") + "\n"
