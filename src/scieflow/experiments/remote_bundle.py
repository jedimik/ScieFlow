"""Remote campaign bundle, generated scripts and transfer check (M-D3 plan 5.3).

Pure Python: this module never starts a process and never touches the network.
Every value written into a generated script is shlex.quote'd, and no generated
script writes a host name. Refusals (links, an existing folder, a missing .sif)
happen before anything is written.
"""

from __future__ import annotations

import hashlib
import os
import posixpath
import re
import shlex
import shutil
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from . import manifest
from .runner import stage_argv
from .stage import sif_path

MODES = ("apptainer", "direct")
STAMP = "+%Y-%m-%dT%H:%M:%S+00:00"
_SUM_LINE = re.compile(r"[0-9a-f]{64}  (artifacts|logs)/[^\\\r\n]+")
_EXIT = re.compile(r"[0-9]{1,3}\n?")
_ENV = re.compile(r"(system|machine|runtime)=([\w .,:()+\-/]{0,120})")


class BundleError(ValueError):
    """A refusal raised before anything is written (plan 5.3)."""


@dataclass(frozen=True)
class Layout:
    """The remote layout of plan 5.3: R/bundle/{stage,input}, R/runs/<id>/."""

    remote_dir: str
    input_name: str

    @property
    def stage_dir(self) -> str:
        return posixpath.join(self.remote_dir, "bundle", "stage")

    @property
    def input_dir(self) -> str:
        return posixpath.join(self.remote_dir, "bundle", "input")

    @property
    def input_path(self) -> str:
        return posixpath.join(self.input_dir, self.input_name)

    def run_dir(self, run_id: str) -> str:
        return posixpath.join(self.remote_dir, "runs", run_id)

    def artifacts_dir(self, run_id: str) -> str:
        return posixpath.join(self.run_dir(run_id), "artifacts")

    def sif(self, stage) -> str:
        return posixpath.join(self.stage_dir, "env", f"{stage.name}.sif")


@dataclass(frozen=True)
class Markers:
    """The marker files of one remote run (plan 5.3 read_markers)."""

    exit_code: int | None  # None: no valid exit marker (no-exit-marker)
    started: str | None
    finished: str | None
    times_from_fetch: bool  # True when a time was unreadable and the fetch time is used
    system: str | None
    machine: str | None
    runtime: str | None


def direct_python(scheduler: str) -> str:
    """The interpreter of a direct (development-only) run (plan 5.3)."""
    return sys.executable if scheduler == "local" else "python3"


def runtime_for(mode: str, python: str) -> str:
    return "apptainer" if mode == "apptainer" else python


def _check_mode(mode: str) -> None:
    if mode not in MODES:
        raise BundleError(f"unknown mode '{mode}' (supported: {', '.join(MODES)})")


def task_argv(stage, spec, layout: Layout, mode: str, python: str) -> list[str]:
    """The argv of one run on the remote, with remote paths (plan 5.3)."""
    _check_mode(mode)
    artifacts = layout.artifacts_dir(spec.run_id)
    if mode == "direct":
        return stage_argv(layout.stage_dir, stage.script, spec, layout.input_path,
                          artifacts, python=python)
    inner = stage_argv(layout.stage_dir, stage.script, spec, layout.input_path,
                       artifacts, python="python")
    binds = sorted({layout.input_dir, layout.stage_dir, layout.run_dir(spec.run_id)})
    cmd = ["apptainer", "exec"]
    for bind in binds:
        cmd += ["--bind", bind]
    return cmd + [layout.sif(stage)] + inner


def _task_script(layout: Layout, spec, argv: list[str], runtime: str) -> str:
    q = shlex.quote
    argv_line = " ".join(q(a) for a in argv)
    env_line = (
        "{ printf 'system=%s\\n' \"$(uname -s)\"; printf 'machine=%s\\n' \"$(uname -m)\"; "
        "printf 'runtime=%s\\n' \"$(" + q(runtime) + " --version 2>&1 | head -n 1)\"; }"
        " > \"$run/remote/environment.txt\""
    )
    lines = [
        "#!/bin/bash",
        "# Generated by scieflow experiment sweep (M-D3). Do not edit.",
        "set -u",
        f"cd {q(layout.remote_dir)} || exit 97",
        f"run={q('runs/' + spec.run_id)}",
        'if [ -e "$run/remote/exit" ]; then exit 0; fi',
        'mkdir -p "$run/artifacts" "$run/logs" "$run/remote" || exit 96',
        f'date -u {STAMP} > "$run/remote/started"',
        env_line,
        f'{argv_line} > "$run/logs/stdout.log" 2> "$run/logs/stderr.log" < /dev/null',
        "rc=$?",
        f'date -u {STAMP} > "$run/remote/finished"',
        '( cd "$run" && find artifacts logs -type f -print0 | LC_ALL=C sort -z'
        ' | xargs -0 -r sha256sum ) > "$run/remote/SHA256SUMS.tmp"'
        ' && mv "$run/remote/SHA256SUMS.tmp" "$run/remote/SHA256SUMS"',
        "printf '%s\\n' \"$rc\" > \"$run/remote/exit.tmp\""
        " && mv \"$run/remote/exit.tmp\" \"$run/remote/exit\"",
        'exit "$rc"',
    ]
    return "\n".join(lines) + "\n"


def _job_script(layout: Layout, n: int) -> str:
    lines = [
        "#!/bin/bash",
        "# Generated by scieflow experiment sweep (M-D3). Do not edit.",
        f"cd {shlex.quote(layout.remote_dir)} || exit 97",
        'if [ -n "${SCIEFLOW_TASK-}" ]; then',
        "  case \"$SCIEFLOW_TASK\" in ''|*[!0-9]*) exit 98;; esac",
        '  exec bash "tasks/$SCIEFLOW_TASK.sh"',
        "fi",
        "rc=0",
        f'for k in $(seq 0 {n - 1}); do bash "tasks/$k.sh" || rc=1; done',
        'exit "$rc"',
    ]
    return "\n".join(lines) + "\n"


def _write_exec(path: Path, text: str) -> None:
    path.write_text(text)
    os.chmod(path, 0o755)


def _refuse_links(root: Path) -> None:
    if root.is_symlink():
        raise BundleError(f"refuses a symlink in the bundle: {root}")
    if root.is_dir():
        for cur, dirs, files in os.walk(root):
            for name in dirs + files:
                path = os.path.join(cur, name)
                if os.path.islink(path):
                    raise BundleError(f"refuses a symlink in the bundle: {path}")


def _copy_file(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(src, dst)  # a hard link where the filesystem allows it
    except OSError:
        shutil.copy2(src, dst)


def _copy_tree(src: Path, dst: Path) -> None:
    for cur, dirs, files in os.walk(src):
        dirs[:] = sorted(d for d in dirs if d != "__pycache__")
        rel = os.path.relpath(cur, src)
        target = dst if rel == "." else dst / rel
        target.mkdir(parents=True, exist_ok=True)
        for name in sorted(files):
            _copy_file(Path(cur) / name, target / name)


def build_bundle(campaign, stage, tasks, mode: str, dest, *, remote_root: str, python: str) -> dict:
    """Write the campaign bundle into `dest` (plan 5.3); return its tree digest."""
    _check_mode(mode)
    tasks = list(tasks)
    if not tasks:
        raise BundleError("a remote campaign needs at least one run")
    dest = Path(dest)
    if os.path.lexists(dest):
        raise BundleError(f"{dest} already exists; a bundle is never written over")
    stage_src = Path(stage.dir)
    input_src = Path(campaign.input)
    if not os.path.lexists(input_src):
        raise BundleError(f"campaign input not found: {input_src}")
    _refuse_links(stage_src)
    _refuse_links(input_src)
    if mode == "apptainer" and not sif_path(stage).exists():
        raise BundleError(
            f"{sif_path(stage)} not built — run: scieflow experiment env build {stage.dir}"
        )
    layout = Layout(remote_root, input_src.name)
    dest.mkdir(parents=True)
    _copy_tree(stage_src, dest / "bundle" / "stage")
    input_dst = dest / "bundle" / "input" / input_src.name
    if input_src.is_dir():
        _copy_tree(input_src, input_dst)
    else:
        _copy_file(input_src, input_dst)
    (dest / "tasks").mkdir()
    runtime = runtime_for(mode, python)
    for k, spec in enumerate(tasks):
        argv = task_argv(stage, spec, layout, mode, python)
        _write_exec(dest / "tasks" / f"{k}.sh", _task_script(layout, spec, argv, runtime))
    _write_exec(dest / "job.sh", _job_script(layout, len(tasks)))
    return manifest.tree_digest(dest)


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _has_link(root: Path) -> bool:
    for cur, dirs, files in os.walk(root):
        for name in dirs + files:
            if os.path.islink(os.path.join(cur, name)):
                return True
    return False


def verify_transfer(run_dir) -> tuple[bool, str | None, int]:
    """Check a fetched run folder against its remote/SHA256SUMS (plan 5.3).

    Returns (ok, reason, files). Reasons: fetched-symlink, transfer-missing,
    transfer-hash (also a malformed checksum list), transfer-extra.
    """
    run = Path(run_dir)
    if run.is_symlink() or _has_link(run):
        return False, "fetched-symlink", 0
    sums = run / "remote" / "SHA256SUMS"
    if not sums.is_file():
        return False, "transfer-missing", 0
    try:
        text = sums.read_bytes().decode("utf-8")
    except UnicodeDecodeError:
        return False, "transfer-hash", 0
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    listed: dict[str, str] = {}
    for line in lines:
        if not _SUM_LINE.fullmatch(line):
            return False, "transfer-hash", 0
        rel = line[66:]
        if any(part in ("", ".", "..") for part in rel.split("/")) or rel in listed:
            return False, "transfer-hash", 0
        listed[rel] = line[:64]
    for rel, digest in listed.items():
        path = run / rel
        if path.is_symlink() or not path.is_file() or _sha256_file(path) != digest:
            return False, "transfer-hash", 0
    for sub in ("artifacts", "logs"):
        base = run / sub
        if not base.is_dir():
            continue
        for cur, _dirs, files in os.walk(base):
            for name in files:
                rel = Path(cur, name).relative_to(run).as_posix()
                if rel not in listed:
                    return False, "transfer-extra", 0
    return True, None, len(listed)


def _read_small(path: Path) -> str | None:
    if not path.is_file() or path.is_symlink():
        return None
    return path.read_bytes()[:4096].decode("utf-8", errors="replace")


def _read_exit(path: Path) -> int | None:
    text = _read_small(path)
    if text is None or not _EXIT.fullmatch(text):
        return None
    value = int(text.strip())
    return value if value <= 255 else None


def _read_time(path: Path, fetched_at: str) -> tuple[str, bool]:
    text = _read_small(path)
    if text is not None:
        try:
            datetime.fromisoformat(text.strip())
            return text.strip(), False
        except ValueError:
            pass
    return fetched_at, True


def read_markers(run_dir, fetched_at: str) -> Markers:
    """Read the marker files of a fetched run (plan 5.3); unreadable parts become None."""
    remote = Path(run_dir) / "remote"
    started, started_flag = _read_time(remote / "started", fetched_at)
    finished, finished_flag = _read_time(remote / "finished", fetched_at)
    env: dict[str, str] = {}
    env_text = _read_small(remote / "environment.txt") or ""
    for line in env_text.splitlines():
        match = _ENV.fullmatch(line)
        if match:
            env[match.group(1)] = match.group(2)
    return Markers(
        exit_code=_read_exit(remote / "exit"),
        started=started,
        finished=finished,
        times_from_fetch=started_flag or finished_flag,
        system=env.get("system"),
        machine=env.get("machine"),
        runtime=env.get("runtime"),
    )
