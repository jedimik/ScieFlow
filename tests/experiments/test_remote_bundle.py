def test_symlink_in_stage_is_refused_naming_the_path(tmp_path):
    stage = make_stage(tmp_path)
    (stage.dir / "link.txt").symlink_to(stage.dir / "run.py")
    inp = make_input(tmp_path)
    with pytest.raises(rb.BundleError, match=re.escape("link.txt")):
        rb.build_bundle(make_campaign(inp), stage, SPECS, "direct", tmp_path / "B",
                        remote_root=R, python="/usr/bin/python3")
    assert not (tmp_path / "B").exists()


