def test_job_script_golden_for_three_runs(tmp_path):
    stage = make_stage(tmp_path)
    inp = make_input(tmp_path)
    dest = tmp_path / "B"
    rb.build_bundle(make_campaign(inp), stage, SPECS, "direct", dest,
                    remote_root=R, python="/usr/bin/python3")
    assert (dest / "job.sh").read_text() == JOB_TEMPLATE.format(R=R, last=2)


@pytest.mark.parametrize("mode", ["direct", "apptainer"])
def test_task_script_golden(tmp_path, mode):
    stage = make_stage(tmp_path, sif=(mode == "apptainer"))
    inp = make_input(tmp_path)
    dest = tmp_path / "B"
    rb.build_bundle(make_campaign(inp), stage, SPECS[:1], mode, dest,
                    remote_root=R, python="/usr/bin/python3")
    if mode == "direct":
        argv = expected_direct_argv("000_gain-0.5", "0.5", "/usr/bin/python3")
        runtime = "/usr/bin/python3"
    else:
        run = f"{R}/runs/000_gain-0.5"
        argv = [
            "apptainer", "exec",
            "--bind", f"{R}/bundle/input",
            "--bind", f"{R}/bundle/stage",
            "--bind", run,
            f"{R}/bundle/stage/env/scale.sif",
            "python", f"{R}/bundle/stage/run.py",
            "--input", f"{R}/bundle/input/noisy.png",
            "--output", f"{run}/artifacts",
            "--gain", "0.5",
        ]
        runtime = "apptainer"
    expected = TASK_TEMPLATE.format(R=R, rid="000_gain-0.5", runtime=runtime, argv=join(argv))
    assert (dest / "tasks" / "0.sh").read_text() == expected


def test_hostile_values_stay_single_argv_elements(tmp_path):
    stage = make_stage(tmp_path, script="run script.py")
    inp = make_input(tmp_path)
    hostile = RunSpec(run_id="000_hostile", params={"label": "a'b; touch PWNED"})
    dest = tmp_path / "B"
    rb.build_bundle(make_campaign(inp), stage, [hostile], "direct", dest,
                    remote_root=R, python="/usr/bin/python3")
    text = (dest / "tasks" / "0.sh").read_text()
    line = next(ln for ln in text.splitlines() if "run script.py" in ln)
    tokens = shlex.split(line.split(" > ")[0])
    assert tokens == [
        "/usr/bin/python3", f"{R}/bundle/stage/run script.py",
        "--input", f"{R}/bundle/input/noisy.png",
        "--output", f"{R}/runs/000_hostile/artifacts",
        "--label", "a'b; touch PWNED",
    ]
    assert not any(ln.startswith("touch ") for ln in text.splitlines())


# ---- bundle builder (plan 5.3) ----

def test_build_bundle_layout_modes_and_digest(tmp_path):
    stage = make_stage(tmp_path)
    inp = make_input(tmp_path)
    dest = tmp_path / "B"
    digest = rb.build_bundle(make_campaign(inp), stage, SPECS, "direct", dest,
                             remote_root=R, python="/usr/bin/python3")
    assert (dest / "bundle" / "stage" / "run.py").is_file()
    assert (dest / "bundle" / "stage" / "stage.yaml").is_file()
    assert (dest / "bundle" / "input" / "noisy.png").read_bytes() == b"NOISY-INPUT"
    assert (dest / "job.sh").stat().st_mode & 0o777 == 0o755
    for k in range(3):
        assert (dest / "tasks" / f"{k}.sh").stat().st_mode & 0o777 == 0o755
    assert not (dest / "runs").exists()
    assert digest == manifest.tree_digest(dest)


def test_sif_is_a_hard_link_on_the_same_filesystem(tmp_path):
    stage = make_stage(tmp_path, sif=True)
    inp = make_input(tmp_path)
    dest = tmp_path / "B"
    rb.build_bundle(make_campaign(inp), stage, SPECS[:1], "apptainer", dest,
                    remote_root=R, python="/usr/bin/python3")
    bundled = dest / "bundle" / "stage" / "env" / "scale.sif"
    assert os.stat(bundled).st_ino == os.stat(stage.dir / "env" / "scale.sif").st_ino


def test_sif_is_copied_when_hard_link_fails(tmp_path, monkeypatch):
    stage = make_stage(tmp_path, sif=True)
    inp = make_input(tmp_path)
    dest = tmp_path / "B"

    def no_links(src, dst, *a, **k):
        raise OSError(errno.EXDEV, "cross-device link")

    monkeypatch.setattr(os, "link", no_links)
    rb.build_bundle(make_campaign(inp), stage, SPECS[:1], "apptainer", dest,
                    remote_root=R, python="/usr/bin/python3")
    bundled = dest / "bundle" / "stage" / "env" / "scale.sif"
    assert bundled.read_bytes() == b"SIF-BYTES"
    assert os.stat(bundled).st_ino != os.stat(stage.dir / "env" / "scale.sif").st_ino


