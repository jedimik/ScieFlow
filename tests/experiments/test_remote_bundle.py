# Plan 5.3, verbatim templates. {R}, {rid}, {runtime}, {argv} are the only holes.
TASK_TEMPLATE = """#!/bin/bash
# Generated by scieflow experiment sweep (M-D3). Do not edit.
set -u
cd {R} || exit 97
run=runs/{rid}
if [ -e "$run/remote/exit" ]; then exit 0; fi
mkdir -p "$run/artifacts" "$run/logs" "$run/remote" || exit 96
date -u +%Y-%m-%dT%H:%M:%S+00:00 > "$run/remote/started"
{{ printf 'system=%s\\n' "$(uname -s)"; printf 'machine=%s\\n' "$(uname -m)"; printf 'runtime=%s\\n' "$({runtime} --version 2>&1 | head -n 1)"; }} > "$run/remote/environment.txt"
{argv} > "$run/logs/stdout.log" 2> "$run/logs/stderr.log" < /dev/null
rc=$?
date -u +%Y-%m-%dT%H:%M:%S+00:00 > "$run/remote/finished"
( cd "$run" && find artifacts logs -type f -print0 | LC_ALL=C sort -z | xargs -0 -r sha256sum ) > "$run/remote/SHA256SUMS.tmp" && mv "$run/remote/SHA256SUMS.tmp" "$run/remote/SHA256SUMS"
printf '%s\\n' "$rc" > "$run/remote/exit.tmp" && mv "$run/remote/exit.tmp" "$run/remote/exit"
exit "$rc"
"""

JOB_TEMPLATE = """#!/bin/bash
# Generated by scieflow experiment sweep (M-D3). Do not edit.
cd {R} || exit 97
if [ -n "${{SCIEFLOW_TASK-}}" ]; then
  case "$SCIEFLOW_TASK" in ''|*[!0-9]*) exit 98;; esac
  exec bash "tasks/$SCIEFLOW_TASK.sh"
fi
rc=0
for k in $(seq 0 {last}); do bash "tasks/$k.sh" || rc=1; done
exit "$rc"
"""


def make_stage(root: Path, script: str = "run.py", sif: bool = False) -> Stage:
    d = root / "pipelines" / "demo" / "stages" / "scale"
    d.mkdir(parents=True)
    (d / "stage.yaml").write_text(STAGE_YAML.format(script=script))
    (d / script).write_text("print('stage')\n")
    if sif:
        (d / "env").mkdir()
        (d / "env" / "scale.sif").write_bytes(b"SIF-BYTES")
    return Stage.load(d)


def make_input(root: Path) -> Path:
    inp = root / "data" / "noisy.png"
    inp.parent.mkdir(parents=True, exist_ok=True)
    inp.write_bytes(b"NOISY-INPUT")
    return inp


def make_campaign(inp: Path) -> Campaign:
    return Campaign(
        name="gain-sweep", pipeline="demo", stage="scale", input=inp,
        reference=None, metrics=["ssim"],
    )


SPECS = [
    RunSpec(run_id="000_gain-0.5", params={"gain": 0.5}),
    RunSpec(run_id="001_gain-1.0", params={"gain": 1.0}),
    RunSpec(run_id="002_gain-2.0", params={"gain": 2.0}),
]


def expected_direct_argv(rid: str, gain: str, python: str) -> list[str]:
    run = f"{R}/runs/{rid}"
    return [
        python, f"{R}/bundle/stage/run.py",
        "--input", f"{R}/bundle/input/noisy.png",
        "--output", f"{run}/artifacts",
        "--gain", gain,
    ]


def join(argv: list[str]) -> str:
    return " ".join(shlex.quote(a) for a in argv)


# ---- task argv (plan 5.3) ----

def test_task_argv_apptainer_binds_sif_and_inner_argv(tmp_path):
    stage = make_stage(tmp_path, sif=True)
    layout = rb.Layout(R, "noisy.png")
    spec = RunSpec(run_id="000_gain-0.5", params={"gain": 0.5}, seed=3)
    argv = rb.task_argv(stage, spec, layout, "apptainer", "/usr/bin/python3")
    run = f"{R}/runs/000_gain-0.5"
    assert argv == [
        "apptainer", "exec",
        "--bind", f"{R}/bundle/input",
        "--bind", f"{R}/bundle/stage",
        "--bind", run,
        f"{R}/bundle/stage/env/scale.sif",
        "python", f"{R}/bundle/stage/run.py",
        "--input", f"{R}/bundle/input/noisy.png",
        "--output", f"{run}/artifacts",
        "--gain", "0.5", "--seed", "3",
    ]


def test_task_argv_direct_uses_given_python(tmp_path):
    stage = make_stage(tmp_path)
    layout = rb.Layout(R, "noisy.png")
    spec = RunSpec(run_id="000_gain-0.5", params={"gain": 0.5})
    argv = rb.task_argv(stage, spec, layout, "direct", "/usr/bin/python3")
    assert argv == expected_direct_argv("000_gain-0.5", "0.5", "/usr/bin/python3")
    assert "apptainer" not in argv


