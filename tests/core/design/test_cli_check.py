"""M-D1 t3: `scieflow design init | check | render | show` (plan 5.7). Synthetic data only.

The CLI reads the repo's schemas and config/reporting through `design_cli._root`, which these
tests point at a temporary root that holds copies of those trees and a run under workspace/.
"""

import json
import shutil
from pathlib import Path

import pytest
from click.testing import CliRunner

from scieflow.core.design import cli as design_cli

REPO = Path(__file__).resolve().parents[3]
FIX = REPO / "tests" / "fixtures" / "design"
STUDY_TYPES = ["rct", "cohort", "case-control", "cross-sectional", "diagnostic-accuracy",
               "prediction-model", "systematic-review", "animal", "economic-evaluation",
               "computational"]


@pytest.fixture
def root(tmp_path, monkeypatch):
    r = tmp_path / "root"
    (r / "workspace").mkdir(parents=True)
    shutil.copytree(REPO / "config" / "reporting", r / "config" / "reporting")
    (r / "schemas").mkdir()
    for name in ("design.yml", "reporting-checklist.yml"):
        shutil.copy(REPO / "schemas" / name, r / "schemas" / name)
    monkeypatch.setattr(design_cli, "_root", lambda: r)
    (r / "workspace" / "run1").mkdir()
    return r


def _run(*args):
    return CliRunner().invoke(design_cli.design, list(args))


def _install(root, name):
    dest = root / "workspace" / "run1" / "design"
    (dest / "power").mkdir(parents=True, exist_ok=True)
    shutil.copy(FIX / f"{name}.yml", dest / "design.yml")
    shutil.copy(FIX / "power-rct-ttest.json", dest / "power" / "rct-ttest.json")


@pytest.mark.parametrize("study_type", STUDY_TYPES)
def test_init_template_reports_only_todo_errors(root, study_type):
    assert _run("init", "run1", "--type", study_type).exit_code == 0
    result = _run("check", "run1", "--json")
    assert result.exit_code == 1
    payload = json.loads(result.output)
    assert payload["errors"], "a fresh template must have TODO errors"
    assert {e["rule"] for e in payload["errors"]} == {"todo"}, payload["errors"]


def test_init_refuses_an_existing_file_until_forced(root):
    assert _run("init", "run1", "--type", "rct").exit_code == 0
    refused = _run("init", "run1", "--type", "cohort")
    assert refused.exit_code == 1
    assert "--force" in refused.output
    assert _run("init", "run1", "--type", "cohort", "--force").exit_code == 0


def test_init_rejects_an_unknown_study_type_and_a_missing_run(root):
    assert _run("init", "run1", "--type", "trial").exit_code == 2
    assert _run("init", "no-such-run", "--type", "rct").exit_code == 2


def test_check_of_a_clean_fixture_exits_zero_and_is_deterministic(root):
    _install(root, "rct")
    first = _run("check", "run1", "--json")
    second = _run("check", "run1", "--json")
    assert first.exit_code == 0, first.output
    assert first.output == second.output
    assert json.loads(first.output)["errors"] == []


def test_check_without_a_design_file_is_a_usage_error(root):
    assert _run("check", "run1").exit_code == 2


def test_check_reports_a_symlinked_design_file_as_invalid(root, tmp_path):
    dest = root / "workspace" / "run1" / "design"
    dest.mkdir(parents=True)
    target = tmp_path / "outside.yml"
    target.write_text((FIX / "rct.yml").read_text(encoding="utf-8"), encoding="utf-8")
    (dest / "design.yml").symlink_to(target)
    result = _run("check", "run1", "--json")
    assert result.exit_code == 1
    assert json.loads(result.output)["errors"][0]["rule"] == "invalid"


def test_check_output_never_echoes_a_free_text_value(root):
    _install(root, "rct")
    path = root / "workspace" / "run1" / "design" / "design.yml"
    path.write_text(path.read_text(encoding="utf-8").replace(
        "study_type: rct", "study_type: Jan Novak 720101/1234"), encoding="utf-8")
    result = _run("check", "run1")
    assert result.exit_code == 1
    assert "Jan Novak" not in result.output and "720101" not in result.output


def test_render_writes_design_md_identically_twice(root):
    _install(root, "rct")
    assert _run("render", "run1").exit_code == 0
    md = root / "workspace" / "run1" / "design" / "design.md"
    first = md.read_bytes()
    assert _run("render", "run1").exit_code == 0
    assert md.read_bytes() == first
    assert first.decode("utf-8").startswith("<!-- generated by scieflow design render from design.yml sha256 ")


def test_show_reports_none_invalid_and_draft(root):
    none = json.loads(_run("show", "run1", "--json").output)
    assert none["status"] == "none"
    _install(root, "rct")
    draft = json.loads(_run("show", "run1", "--json").output)
    assert draft["status"] == "draft"
    assert draft["sap_metrics"] == ["score_mse"]
    assert len(draft["content_hash"]) == 64
    (root / "workspace" / "run1" / "design" / "design.yml").write_text("- not a mapping\n", encoding="utf-8")
    invalid = json.loads(_run("show", "run1", "--json").output)
    assert invalid["status"] == "invalid"
