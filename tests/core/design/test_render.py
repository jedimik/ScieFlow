"""M-D1 t3: design.md rendering (plan 5.2 `render`): deterministic, fixed section order, hash line.

Synthetic fixtures only.
"""

from pathlib import Path

import yaml

from scieflow.core.design import model
from scieflow.core.design import render as design_render

REPO = Path(__file__).resolve().parents[3]
FIX = REPO / "tests" / "fixtures" / "design"

HEADINGS = [
    "## Study type",
    "## Question and PICO",
    "## Variables",
    "## Groups",
    "## Timeline",
    "## Sampling",
    "## Randomisation and blinding",
    "## Sample size",
    "## Statistical analysis plan",
    "## Reporting guidelines",
    "## Data levels",
    "## Check result",
]


def _doc(name):
    return yaml.safe_load((FIX / f"{name}.yml").read_text(encoding="utf-8"))


def _render(name, tmp_path, power=None):
    from scieflow.core.project import Project

    ws = tmp_path / "workspace" / "run1"
    (ws / "design" / "power").mkdir(parents=True, exist_ok=True)
    design = _doc(name)
    report = model.check(Project(REPO), ws, design)
    digest = model.content_hash(design)
    return design_render.render(design, report, digest, power=power), digest


def test_first_line_names_the_generator_and_the_hash(tmp_path):
    text, digest = _render("rct", tmp_path)
    first = text.splitlines()[0]
    assert first == (f"<!-- generated by scieflow design render from design.yml sha256 {digest}; "
                     "do not edit -->")


def test_section_headings_appear_once_and_in_the_plan_order(tmp_path):
    text, _ = _render("rct", tmp_path)
    positions = [text.index(heading) for heading in HEADINGS]
    assert positions == sorted(positions)
    assert all(text.count(heading) == 1 for heading in HEADINGS)


def test_title_is_the_level_one_heading(tmp_path):
    text, _ = _render("rct", tmp_path)
    assert "\n# Synthetic two-arm trial (fixture)\n" in text


def test_same_input_gives_identical_bytes(tmp_path):
    first, _ = _render("cohort", tmp_path)
    second, _ = _render("cohort", tmp_path)
    assert first == second


def test_power_section_shows_the_family_and_result_when_a_power_file_is_given(tmp_path):
    import json

    power_doc = json.loads((FIX / "power-rct-ttest.json").read_text(encoding="utf-8"))
    text, _ = _render("rct", tmp_path, power=power_doc)
    assert "t-ind" in text
    assert "n1_required" in text


def test_check_result_lists_rule_ids_not_values(tmp_path):
    text, _ = _render("computational", tmp_path)
    assert "## Check result" in text
    assert "errors: 0" in text
